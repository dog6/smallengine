Vec2f::Vec2f()
{
    this->x = 0.0f;
    this->y = 0.0f;
}

Vec2f::Vec2f(float _x, float _y)
{
    this->x = _x;
    this->y = _y;
}

Vec2::Vec2()
{
    this->x = 0;
    this->y = 0;
}

Vec2::Vec2(int _x, int _y)
{
    this->x = _x;
    this->y = _y;
}